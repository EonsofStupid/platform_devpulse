/**
 * @file scripts/dev/design/sd/formats/tailwind-theme.ts
 * @package @devpulse/coldlight
 *
 * Registers the `coldlight/tailwind-theme` SD5 format.
 *
 * Uses dictionary.allTokens — SD5's processed token list.
 * Maps tokens to Tailwind v4 @theme variable names using
 * tokensConfig.themeMappings as SSOT.
 *
 * Output: @theme { --color-glass-void: oklch(...); ... }
 */

import StyleDictionary from "style-dictionary";
import type { Format } from "style-dictionary/types";

type Mapping = { namespace: string; prefix: string | null };
type Mappings = Record<string, Mapping>;

export function registerTailwindTheme(mappings: Mappings): void {
	const format: Format = {
		name: "coldlight/tailwind-theme",
		format: ({ dictionary }) => {
			const lines: string[] = [
				"/**",
				" * AUTO-GENERATED — DO NOT EDIT",
				" * Tailwind v4 @theme block — generated by pnpm ds:tokens:build",
				" */",
				"",
				"@theme {",
			];

			dictionary.allTokens.forEach((token) => {
				const group = token.path[0];
				const mapping = mappings[group];
				if (!mapping) return; // token not mapped to a Tailwind utility

				const value = token.$value ?? token.value;
				const suffix = token.path.slice(1).join("-");
				const varKey = mapping.prefix
					? `--${mapping.namespace}-${mapping.prefix}-${suffix}`
					: `--${mapping.namespace}-${suffix}`;

				lines.push(`\t${varKey}: ${value};`);
			});

			lines.push("}");
			lines.push("");

			return lines.join("\n");
		},
	};

	StyleDictionary.registerFormat(format);
}
