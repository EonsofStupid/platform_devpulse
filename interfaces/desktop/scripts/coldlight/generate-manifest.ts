#!/usr/bin/env npx tsx
/**
 * @file ColdLight Generator
 * @package @devpulse/coldlight
 *
 * Runs the scanner and writes both the manifest AND the import cloak to disk.
 *
 * Outputs:
 *   1. coldlight.manifest.json — JSON manifest of all primitives
 *   2. imports.gen.ts — The cloak file aliasing adapter factories to ColdLight-generic names
 *
 * Usage: pnpm coldlight:generate
 */

import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DESKTOP_ROOT = path.resolve(__dirname, "../..");
const DESIGN_ROOT = path.resolve(DESKTOP_ROOT, "src/lib/design");

/**
 * Capitalize first letter: "dialog" → "Dialog"
 */
function capitalize(s: string): string {
	return s.charAt(0).toUpperCase() + s.slice(1);
}

/**
 * Generate the imports.gen.ts cloak file content.
 *
 * For each meltui-backed kind, writes:
 *   export { createMelt<Kind> as create<Kind> } from "$lib/design/api/adapters/meltui/_internal/<kind>/factory";
 *   export type { Melt<Kind>Instance as <Kind>Instance } from "...";
 *   export type { Melt<Kind>Config as <Kind>Config } from "...";
 */
function generateImportsCloak(
	kinds: Array<{ kind: string; ariaStateProvider: string }>,
	activeAdapter: string,
): string {
	const lines: string[] = [
		"/**",
		" * AUTO-GENERATED by coldlight:generate — DO NOT EDIT",
		" *",
		" * ColdLight Import Cloak",
		" * Maps adapter-specific factories to ColdLight-generic names.",
		" * Primitives import ONLY from this file. Zero adapter awareness.",
		" *",
		` * Active adapter: ${activeAdapter}`,
		" */",
		"",
	];

	const meltuiKinds = kinds.filter((k) => k.ariaStateProvider === "meltui");

	meltuiKinds.forEach((entry) => {
		const kind = entry.kind;
		const Kind = capitalize(kind);
		const factoryPath = `$lib/design/api/adapters/meltui/_internal/${kind}/factory`;

		lines.push(`// =============================================================================`);
		lines.push(`// ${kind}`);
		lines.push(`// =============================================================================`);
		lines.push(``);
		lines.push(`export { createMelt${Kind} as create${Kind} } from "${factoryPath}";`);
		lines.push(`export type { Melt${Kind}Instance as ${Kind}Instance } from "${factoryPath}";`);
		lines.push(`export type { Melt${Kind}Config as ${Kind}Config } from "${factoryPath}";`);
		lines.push(``);
	});

	return lines.join("\n");
}

async function main() {
	// Dynamic import with pathToFileURL for Windows ESM compatibility
	const configPath = pathToFileURL(path.resolve(DESIGN_ROOT, "coldlight.config.js")).href;
	const scannerPath = pathToFileURL(path.resolve(DESIGN_ROOT, "taxonomy/scanner.js")).href;

	const { coldlightConfig } = await import(configPath);
	const { scanColdLight } = await import(scannerPath);

	// Build import function that resolves relative to design root
	const importFn = async (p: string) => {
		const fullPath = path.resolve(DESKTOP_ROOT, p);
		return import(pathToFileURL(fullPath).href);
	};

	const result = await scanColdLight(fs, importFn, coldlightConfig);

	if (!result.valid) {
		console.error("[ColdLight] Scan failed with errors:");
		for (const err of result.errors) {
			console.error(`  [${err.code}] ${err.kind}: ${err.detail}`);
		}
		process.exit(1);
	}

	if (!result.manifest) {
		return;
	}

	// Ensure output directory exists
	const manifestPath = path.resolve(DESKTOP_ROOT, coldlightConfig.generation.outputs.manifestJson);
	const importsPath = path.resolve(DESKTOP_ROOT, coldlightConfig.generation.outputs.importsTs);
	const outputDir = path.dirname(manifestPath);

	if (!fs.existsSync(outputDir)) {
		fs.mkdirSync(outputDir, { recursive: true });
	}

	// Write manifest JSON
	fs.writeFileSync(manifestPath, `${JSON.stringify(result.manifest, null, 2)}\n`);

	// Write imports cloak
	const kinds = result.manifest.categories.primitives.kinds.map(
		(k: { kind: string; ariaStateProvider: string }) => ({
			kind: k.kind,
			ariaStateProvider: k.ariaStateProvider,
		}),
	);
	const cloakContent = generateImportsCloak(kinds, coldlightConfig.adapters.active);
	fs.writeFileSync(importsPath, cloakContent);
}

main().catch((err) => {
	console.error("[ColdLight] Fatal error:", err);
	process.exit(1);
});
