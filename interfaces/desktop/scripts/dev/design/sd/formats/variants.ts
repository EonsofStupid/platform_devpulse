/**
 * @file scripts/dev/design/sd/formats/variants.ts
 * @package @devpulse/coldlight
 *
 * Generates variants.css — @utility classes from TOKEN_CATEGORY_REGISTRY.
 *
 * Reads the SSOT registry. For each category, for each value,
 * dumps tokenRefs (CSS property:value pairs) directly into @utility blocks.
 * No resolver, no transformation — tokenRefs ARE the CSS output.
 *
 * SHADOW COMPOSITION: Categories d (depth), b (bevel), g (glow), and f (frame)
 * all produce box-shadow values. Instead of setting box-shadow directly (which
 * causes last-one-wins conflicts), they set CSS custom property layers:
 *   --shadow-depth, --shadow-bevel, --shadow-glow, --shadow-frame
 * A base rule composes all layers into one box-shadow declaration.
 * This means v-d2 v-b1 v-g6 all compose correctly.
 *
 * Output: @utility v-s0 { background: transparent; }
 *         @utility v-d1 { --shadow-depth: var(--shadow-z1); }
 *         @utility v-b1 { --shadow-bevel: var(--bevel-subtle); }
 *         @utility v-g1 { --shadow-glow: var(--glow-teal); }
 */

interface CategoryValue {
	index: number;
	id: string;
	label: string;
	tokenRefs: Record<string, string>;
	svgFilters?: string[];
}

interface CategoryDefinition {
	code: string;
	name: string;
	description: string;
	values: CategoryValue[];
	defaultIndex: number;
	encodingOrder: number;
	vpbControl: string;
}

/**
 * Map category codes to their shadow layer custom property name.
 * Categories in this map redirect box-shadow values to layer variables
 * instead of setting box-shadow directly.
 */
const SHADOW_LAYER_MAP: Record<string, string> = {
	d: "--shadow-depth",
	b: "--shadow-bevel",
	g: "--shadow-glow",
};

export function generateVariantsCSS(registry: CategoryDefinition[]): string {
	const lines: string[] = [
		"/**",
		" * AUTO-GENERATED — DO NOT EDIT",
		" * ColdLight variant utilities — generated by pnpm ds:tokens:build",
		" * Source: registry/token-categories.ts → TOKEN_CATEGORY_REGISTRY",
		" *",
		` * Categories: ${registry.map((c) => c.code).join(", ")} (${registry.length} total)`,
		` * Values: ${registry.reduce((sum, c) => sum + c.values.length, 0)} total`,
		" *",
		" * Shadow composition: d (depth), b (bevel), g (glow) set layer vars.",
		" * The base rule composes all layers into one box-shadow.",
		" */",
		"",
		"/* ── Shadow Composition Base ── */",
		"/* All ColdLight-encoded elements compose shadow layers. */",
		"/* Default: all layers are transparent (no shadow). */",
		"@layer base {",
		"\t[data-kind] {",
		"\t\t--shadow-depth: 0 0 0 transparent;",
		"\t\t--shadow-bevel: 0 0 0 transparent;",
		"\t\t--shadow-glow: 0 0 0 transparent;",
		"\t\t--shadow-frame: 0 0 0 transparent;",
		"\t\tbox-shadow: var(--shadow-depth), var(--shadow-bevel), var(--shadow-glow), var(--shadow-frame);",
		"\t}",
		"}",
		"",
	];

	for (const cat of registry) {
		lines.push(`/* ── ${cat.code}: ${cat.name} — ${cat.values.length} values ── */`);

		const shadowLayer = SHADOW_LAYER_MAP[cat.code];

		for (const value of cat.values) {
			const refs = Object.entries(value.tokenRefs);

			if (refs.length === 0) {
				// Tailwind v4 requires at least one property per @utility.
				// Emit an inert custom property marker for "none/default" values.
				lines.push(`@utility v-${cat.code}${value.index} {`);
				lines.push(`\t--v-${cat.code}: ${value.index};`);
				lines.push("}");
				continue;
			}

			lines.push(`@utility v-${cat.code}${value.index} {`);

			for (const [prop, val] of refs) {
				if (prop === "box-shadow" && shadowLayer) {
					// Redirect box-shadow to the layer custom property
					lines.push(`\t${shadowLayer}: ${val};`);
				} else if (prop === "box-shadow" && cat.code === "f") {
					// Frame category: glow border goes to --shadow-frame
					lines.push(`\t--shadow-frame: ${val};`);
				} else {
					lines.push(`\t${prop}: ${val};`);
				}
			}

			if (value.svgFilters && value.svgFilters.length > 0) {
				lines.push(`\t/* svg-filters: ${value.svgFilters.join(", ")} */`);
			}

			lines.push("}");
		}

		lines.push("");
	}

	return lines.join("\n");
}
