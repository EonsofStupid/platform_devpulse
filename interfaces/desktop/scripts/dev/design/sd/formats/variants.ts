/**
 * @file scripts/dev/design/sd/formats/variants.ts
 * @package @devpulse/coldlight
 *
 * Generates variants.css — @utility classes for the variant key system.
 * Reads variantKeys from tokens.ts SSOT.
 *
 * Output: @utility v-s0 { --v-surface: transparent; background: transparent; }
 *         @utility v-s1 { --v-surface: var(--glass-void); background: var(--glass-void); backdrop-filter: ... }
 *         etc.
 */

interface VariantKeyDef {
	cssProperty: string;
	cssVar: string;
	values: readonly string[];
	extras?: readonly string[];
}

type VariantKeys = Record<string, VariantKeyDef>;

export function generateVariantsCSS(variantKeys: VariantKeys): string {
	const lines: string[] = [
		"/**",
		" * AUTO-GENERATED — DO NOT EDIT",
		" * Variant key utilities — generated by pnpm ds:tokens:build",
		" * Source: tokens/tokens.ts → variantKeys",
		" */",
		"",
	];

	for (const [key, def] of Object.entries(variantKeys)) {
		lines.push(`/* v-${key}: ${def.cssProperty} */`);

		for (let i = 0; i < def.values.length; i++) {
			const value = def.values[i];
			const extra = def.extras?.[i] ?? "";

			lines.push(`@utility v-${key}${i} {`);
			lines.push(`\t${def.cssVar}: ${value};`);

			// For surface and depth, also set the CSS property directly
			if (def.cssProperty !== def.cssVar) {
				lines.push(`\t${def.cssProperty}: ${value};`);
			}

			if (extra) {
				lines.push(`\t${extra}`);
			}

			lines.push("}");
		}

		lines.push("");
	}

	return lines.join("\n");
}
