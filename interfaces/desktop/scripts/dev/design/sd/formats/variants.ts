/**
 * @file scripts/dev/design/sd/formats/variants.ts
 * @package @devpulse/coldlight
 *
 * Generates variants.css — @utility classes from TOKEN_CATEGORY_REGISTRY.
 *
 * Reads the SSOT registry. For each category, for each value,
 * dumps tokenRefs (CSS property:value pairs) directly into @utility blocks.
 * No resolver, no transformation — tokenRefs ARE the CSS output.
 *
 * Output: @utility v-s0 { background: transparent; }
 *         @utility v-s1 { background: var(--glass-void); backdrop-filter: ...; }
 */

interface CategoryValue {
	index: number;
	id: string;
	label: string;
	tokenRefs: Record<string, string>;
	svgFilters?: string[];
}

interface CategoryDefinition {
	code: string;
	name: string;
	description: string;
	values: CategoryValue[];
	defaultIndex: number;
	encodingOrder: number;
	vpbControl: string;
}

export function generateVariantsCSS(
	registry: CategoryDefinition[],
): string {
	const lines: string[] = [
		"/**",
		" * AUTO-GENERATED — DO NOT EDIT",
		" * ColdLight variant utilities — generated by pnpm ds:tokens:build",
		" * Source: registry/token-categories.ts → TOKEN_CATEGORY_REGISTRY",
		" *",
		` * Categories: ${registry.map((c) => c.code).join(", ")} (${registry.length} total)`,
		` * Values: ${registry.reduce((sum, c) => sum + c.values.length, 0)} total`,
		" */",
		"",
	];

	for (const cat of registry) {
		lines.push(
			`/* ── ${cat.code}: ${cat.name} — ${cat.values.length} values ── */`,
		);

		for (const value of cat.values) {
			const refs = Object.entries(value.tokenRefs);

			if (refs.length === 0) {
				// Tailwind v4 requires at least one property per @utility.
				// Emit an inert custom property marker for "none/default" values.
				lines.push(`@utility v-${cat.code}${value.index} {`);
				lines.push(`\t--v-${cat.code}: ${value.index};`);
				lines.push("}");
				continue;
			}

			lines.push(`@utility v-${cat.code}${value.index} {`);

			for (const [prop, val] of refs) {
				lines.push(`\t${prop}: ${val};`);
			}

			if (value.svgFilters && value.svgFilters.length > 0) {
				lines.push(
					`\t/* svg-filters: ${value.svgFilters.join(", ")} */`,
				);
			}

			lines.push("}");
		}

		lines.push("");
	}

	return lines.join("\n");
}
