/**
 * @file scripts/dev/design/sd/formats/tailwind-preset.ts
 * @package @devpulse/coldlight
 *
 * Registers the `coldlight/tailwind-preset` SD5 format.
 *
 * Uses dictionary.allTokens — SD5's processed token list.
 * Generates a Tailwind v3 preset with var() references.
 * Filters tokens by path[0] group to populate each preset section.
 *
 * Output: export const dpPreset = { theme: { extend: { ... } } }
 */

import StyleDictionary from "style-dictionary";
import type { Format, TransformedToken } from "style-dictionary/types";

export function registerTailwindPreset(): void {
	const format: Format = {
		name: "coldlight/tailwind-preset",
		format: ({ dictionary }) => {
			const all = dictionary.allTokens;

			// Build nested color object: { teal: { '50': 'var(--color-teal-50)' } }
			const colors: Record<string, Record<string, string>> = {};
			all
				.filter((t: TransformedToken) => t.path[0] === "color")
				.forEach((t: TransformedToken) => {
					const scale = t.path[1];
					const step = t.path[2];
					if (!colors[scale]) colors[scale] = {};
					colors[scale][step] = `var(--${t.name})`;
				});

			const spacing: Record<string, string> = {};
			all
				.filter((t: TransformedToken) => t.path[0] === "space")
				.forEach((t: TransformedToken) => { spacing[t.path[1]] = `var(--${t.name})`; });

			const borderRadius: Record<string, string> = {};
			all
				.filter((t: TransformedToken) => t.path[0] === "radius")
				.forEach((t: TransformedToken) => { borderRadius[t.path[1]] = `var(--${t.name})`; });

			const boxShadow: Record<string, string> = {};
			all
				.filter((t: TransformedToken) => t.path[0] === "glow")
				.forEach((t: TransformedToken) => { boxShadow[`glow-${t.path[1]}`] = `var(--${t.name})`; });
			all
				.filter((t: TransformedToken) => t.path[0] === "shadow")
				.forEach((t: TransformedToken) => { boxShadow[t.path[1]] = `var(--${t.name})`; });

			const zIndex: Record<string, string> = {};
			all
				.filter((t: TransformedToken) => t.path[0] === "z")
				.forEach((t: TransformedToken) => { zIndex[t.path[1]] = `var(--${t.name})`; });

			const lines: string[] = [
				"/**",
				" * AUTO-GENERATED — DO NOT EDIT",
				" * Tailwind v3 preset — generated by pnpm ds:tokens:build",
				" */",
				"",
				"export const dpPreset = {",
				"\ttheme: {",
				"\t\textend: {",
				"\t\t\tcolors: " + JSON.stringify(colors, null, "\t\t\t\t").replace(/\n/g, "\n\t\t\t") + ",",
				"\t\t\tspacing: " + JSON.stringify(spacing, null, "\t\t\t\t").replace(/\n/g, "\n\t\t\t") + ",",
				"\t\t\tborderRadius: " + JSON.stringify(borderRadius, null, "\t\t\t\t").replace(/\n/g, "\n\t\t\t") + ",",
				"\t\t\tboxShadow: " + JSON.stringify(boxShadow, null, "\t\t\t\t").replace(/\n/g, "\n\t\t\t") + ",",
				"\t\t\tzIndex: " + JSON.stringify(zIndex, null, "\t\t\t\t").replace(/\n/g, "\n\t\t\t") + ",",
				"\t\t},",
				"\t},",
				"} as const;",
				"",
			];

			return lines.join("\n");
		},
	};

	StyleDictionary.registerFormat(format);
}
