/**
 * @file scripts/dev/design/sd/formats/types.ts
 * @package @devpulse/coldlight
 *
 * Registers the `coldlight/types` SD5 format.
 *
 * EXCEPTION: Uses jiti-imported `tokens.enums` directly — not dictionary.allTokens.
 * Reason: DTCG $value is a scalar. Token enum arrays (readonly string[])
 * cannot be represented as DTCG tokens. This format is the only one
 * that reads raw TS imports.
 *
 * Output: TypeScript union types + runtime arrays from tokens.enums.
 */

import StyleDictionary from "style-dictionary";
import type { Format } from "style-dictionary/types";

type Enums = Record<string, readonly (string | number)[]>;

export function registerTypes(jitiEnums: Enums): void {
	const format: Format = {
		name: "coldlight/types",
		format: () => {
			const lines: string[] = [
				"/**",
				" * @file types.ts",
				" * @package @devpulse/coldlight",
				" *",
				" * AUTO-GENERATED — DO NOT EDIT",
				" * Generated by pnpm ds:tokens:build from tokens.enums",
				" */",
				"",
			];

			for (const [name, values] of Object.entries(jitiEnums)) {
				const pascal = name.charAt(0).toUpperCase() + name.slice(1);
				const serialized = JSON.stringify([...values]);
				lines.push(`export const ${pascal}Tokens = ${serialized} as const;`);
				lines.push(
					`export type ${pascal}Token = (typeof ${pascal}Tokens)[number];`,
				);
				lines.push("");
			}

			lines.push("export const TokenArrays = {");
			for (const name of Object.keys(jitiEnums)) {
				const pascal = name.charAt(0).toUpperCase() + name.slice(1);
				lines.push(`\t${name}: ${pascal}Tokens,`);
			}
			lines.push("} as const;");
			lines.push("");

			return lines.join("\n");
		},
	};

	StyleDictionary.registerFormat(format);
}
