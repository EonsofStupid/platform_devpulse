/**
 * @file scripts/dev/design/sd/build-unified.ts
 * @package @devpulse/coldlight
 *
 * Unified ColdLight build pipeline — ONE command, ONE manifest.
 *
 * Usage: pnpm ds:build:full
 *
 * Pipeline:
 *   1. SD5 token build (tokens.css, tailwind.css, types.ts, DTCG)
 *   2. Generated CSS (variants.css, typography.css, focus.css, scrollbars.css, keyframes.css)
 *   3. Scanner (parity=warn) → primitives, components, recipes, effects, SVG
 *   4. Merge token data + scanner data → ONE unified manifest
 *   5. Report: summary of everything cataloged
 *
 * Output: src/lib/design/generated/coldlight.manifest.json  (UNIFIED)
 */

import * as fs from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import StyleDictionary from "style-dictionary";
import { dtcgPath, tokensConfig, jitiEnums, jitiRegistry, jitiKeyframesDef, desktopRoot } from "./preprocessors/ts-to-dtcg.js";
import { buildConfig } from "./config.js";
import { generateVariantsCSS } from "./formats/variants.js";
import {
	generateTypographyCSS,
	generateFocusCSS,
	generateScrollbarsCSS,
} from "./formats/generated-css.js";

const DESIGN_ROOT = resolve(desktopRoot, "src/lib/design");

// =============================================================================
// STEP 1: SD5 TOKEN BUILD
// =============================================================================

console.log("[UNIFIED] Step 1: SD5 token build...");
const config = buildConfig(dtcgPath, tokensConfig, jitiEnums, desktopRoot);
const sd = new StyleDictionary(config);
await sd.buildAllPlatforms();

console.log(`  CSS:   ${tokensConfig.platforms.css.output}`);
console.log(`  Theme: ${tokensConfig.platforms.theme.output}`);
console.log(`  Types: ${tokensConfig.platforms.types.output}`);
console.log(`  DTCG:  ${tokensConfig.dtcg.output}`);

// =============================================================================
// STEP 2: GENERATED CSS
// =============================================================================

console.log("[UNIFIED] Step 2: Generated CSS...");
const generatedDir = resolve(desktopRoot, "src/lib/design/generated");
fs.mkdirSync(generatedDir, { recursive: true });

function generateKeyframesCSS(keyframesDef: Record<string, string>): string {
	const lines: string[] = [
		"/**",
		" * AUTO-GENERATED — DO NOT EDIT",
		" * Animation keyframes — generated by pnpm ds:build:full",
		" * Source: tokens/motion/keyframes.ts → keyframesDef",
		" */",
		"",
	];

	for (const [name, body] of Object.entries(keyframesDef)) {
		lines.push(`@keyframes ${name} {${body}`);
		lines.push("}");
		lines.push("");
	}

	lines.push(`@keyframes fade-in {
	from { opacity: 0; }
	to { opacity: 1; }
}

@keyframes slide-up {
	from { transform: translateY(4px); opacity: 0; }
	to { transform: translateY(0); opacity: 1; }
}

@keyframes slide-down {
	from { transform: translateY(-4px); opacity: 0; }
	to { transform: translateY(0); opacity: 1; }
}

@keyframes scale-in {
	from { transform: scale(0.95); opacity: 0; }
	to { transform: scale(1); opacity: 1; }
}

@keyframes spin {
	from { transform: rotate(0deg); }
	to { transform: rotate(360deg); }
}`);

	return lines.join("\n");
}

const generatedFiles = [
	{ name: "variants.css", content: generateVariantsCSS(jitiRegistry) },
	{ name: "typography.css", content: generateTypographyCSS() },
	{ name: "focus.css", content: generateFocusCSS() },
	{ name: "scrollbars.css", content: generateScrollbarsCSS() },
	{ name: "keyframes.css", content: generateKeyframesCSS(jitiKeyframesDef) },
];

for (const file of generatedFiles) {
	const path = resolve(generatedDir, file.name);
	fs.writeFileSync(path, file.content, "utf-8");
	console.log(`  [GEN] ${file.name}`);
}

// =============================================================================
// STEP 3: SCANNER — primitives, components, recipes, effects
// =============================================================================

console.log("[UNIFIED] Step 3: Scanner...");

const configPath = pathToFileURL(resolve(DESIGN_ROOT, "coldlight.config.js")).href;
const scannerPath = pathToFileURL(resolve(DESIGN_ROOT, "scanner.js")).href;

const { coldlightConfig } = await import(configPath);
const { scanColdLight } = await import(scannerPath);

const importFn = async (p: string) => {
	const fullPath = resolve(desktopRoot, p);
	return import(pathToFileURL(fullPath).href);
};

const scanResult = await scanColdLight(fs, importFn, coldlightConfig);

if (!scanResult.manifest) {
	console.error("[UNIFIED] Scanner FATAL — manifest could not be produced:");
	for (const err of scanResult.errors) {
		console.error(`  [${err.code}] ${err.kind}: ${err.detail}`);
	}
	process.exit(1);
}

if (scanResult.errors.length > 0) {
	console.warn(`  ${scanResult.errors.length} parity warning(s)`);
}

// =============================================================================
// STEP 4: MERGE — ONE UNIFIED MANIFEST
// =============================================================================

console.log("[UNIFIED] Step 4: Merging token + scanner data...");

// Build token data section from SD5 output
const tokenData = {
	pipeline: "sd5-dtcg-1.0" as const,
	encodingCategories: jitiRegistry.map((cat: { code: string; name: string; description: string; encodingOrder: number; defaultIndex: number; vpbControl: string; values: Array<{ index: number; id: string; label: string; tokenRefs: Record<string, string>; svgFilters?: string[] }> }) => ({
		code: cat.code,
		name: cat.name,
		description: cat.description,
		encodingOrder: cat.encodingOrder,
		defaultIndex: cat.defaultIndex,
		vpbControl: cat.vpbControl,
		valueCount: cat.values.length,
		values: cat.values.map((v) => ({
			index: v.index,
			id: v.id,
			label: v.label,
			tokenRefs: v.tokenRefs,
			svgFilters: v.svgFilters ?? [],
		})),
	})),
	encoding: {
		order: jitiRegistry.map((c: { code: string }) => c.code),
		totalValues: jitiRegistry.reduce((s: number, c: { values: unknown[] }) => s + c.values.length, 0),
		format: "v-{code}{index}",
		example: `v-${jitiRegistry.map((c: { code: string }) => `${c.code}0`).join("")}`,
	},
	tokenEnums: Object.fromEntries(
		Object.entries(jitiEnums).map(([key, values]) => [
			key,
			{ values: Array.from(values as readonly unknown[]), count: (values as readonly unknown[]).length },
		]),
	),
	keyframes: Object.keys(jitiKeyframesDef),
	generatedFiles: generatedFiles.map((f) => ({
		file: `generated/${f.name}`,
		bytes: Buffer.byteLength(f.content, "utf-8"),
	})),
	platforms: {
		css: tokensConfig.platforms.css.output,
		theme: tokensConfig.platforms.theme.output,
		types: tokensConfig.platforms.types.output,
		dtcg: tokensConfig.dtcg.output,
	},
};

// Merge: scanner manifest + enriched token data = ONE unified manifest
const unifiedManifest = {
	$schema: "coldlight/manifest/unified",
	version: "1.0.0",
	generatedAt: new Date().toISOString(),
	config: {
		framework: "svelte5",
		adapter: coldlightConfig.adapters.active,
		ariaStateProvider: coldlightConfig.adapters.ariaStateProvider,
	},
	tokens: tokenData,
	primitives: scanResult.manifest.categories.primitives,
	components: scanResult.manifest.categories.components,
	recipes: scanResult.manifest.categories.recipes,
	effects: scanResult.manifest.categories.effects,
	svg: scanResult.manifest.categories.svg,
};

// Write unified manifest — ONE location, ONE file
const unifiedPath = resolve(desktopRoot, "src/lib/design/generated/coldlight.manifest.json");
fs.writeFileSync(unifiedPath, `${JSON.stringify(unifiedManifest, null, "\t")}\n`, "utf-8");

// Write imports cloak to .generated/ (import cloak is separate from manifest)
function capitalize(s: string): string {
	return s.charAt(0).toUpperCase() + s.slice(1);
}

const meltuiKinds = scanResult.manifest.categories.primitives.kinds
	.filter((k: { ariaStateProvider: string }) => k.ariaStateProvider === "meltui");
const cloakLines: string[] = [
	"/**",
	" * AUTO-GENERATED by ds:build:full — DO NOT EDIT",
	" *",
	" * ColdLight Import Cloak",
	" * Maps adapter-specific factories to ColdLight-generic names.",
	" */",
	"",
];
meltuiKinds.forEach((entry: { kind: string }) => {
	const Kind = capitalize(entry.kind);
	const factoryPath = `$lib/design/api/dsadapters/meltui/_internal/${entry.kind}/factory`;
	cloakLines.push(`export { createMelt${Kind} as create${Kind} } from "${factoryPath}";`);
	cloakLines.push(`export type { Melt${Kind}Instance as ${Kind}Instance } from "${factoryPath}";`);
	cloakLines.push(`export type { Melt${Kind}Config as ${Kind}Config } from "${factoryPath}";`);
	cloakLines.push("");
});
const cloakOutputDir = resolve(desktopRoot, "src/lib/design/.generated");
fs.mkdirSync(cloakOutputDir, { recursive: true });
const importsPath = resolve(cloakOutputDir, "imports.gen.ts");
fs.writeFileSync(importsPath, cloakLines.join("\n"), "utf-8");

// =============================================================================
// STEP 5: REPORT
// =============================================================================

const primKinds = unifiedManifest.primitives.kinds;
const complete = primKinds.filter((p: { status: string }) => p.status === "complete").length;
const contractOnly = primKinds.filter((p: { status: string }) => p.status === "contract-only").length;

console.log("");
console.log("╔════════════════════════════════════════════════════════════╗");
console.log("║              ColdLight Unified Build Complete             ║");
console.log("╠════════════════════════════════════════════════════════════╣");
console.log(`║  Primitives:  ${String(primKinds.length).padStart(3)} (${complete} complete, ${contractOnly} contract-only)`.padEnd(61) + "║");
console.log(`║  Components:  ${String(unifiedManifest.components.kinds.length).padStart(3)}`.padEnd(61) + "║");
console.log(`║  Recipes:     ${String(unifiedManifest.recipes.entries.length).padStart(3)}`.padEnd(61) + "║");
console.log(`║  Effects:     ${String(unifiedManifest.effects.definitions.length).padStart(3)}`.padEnd(61) + "║");
console.log(`║  SVG Filters: ${String(unifiedManifest.svg.filters.length).padStart(3)}`.padEnd(61) + "║");
console.log(`║  Token Cats:  ${String(tokenData.encodingCategories.length).padStart(3)} (${tokenData.encoding.totalValues} values)`.padEnd(61) + "║");
console.log(`║  Token Enums: ${String(Object.keys(tokenData.tokenEnums).length).padStart(3)}`.padEnd(61) + "║");
console.log(`║  Keyframes:   ${String(tokenData.keyframes.length).padStart(3)}`.padEnd(61) + "║");
console.log("╠════════════════════════════════════════════════════════════╣");
console.log("║  Output: generated/coldlight.manifest.json (UNIFIED)     ║");
console.log("╚════════════════════════════════════════════════════════════╝");
