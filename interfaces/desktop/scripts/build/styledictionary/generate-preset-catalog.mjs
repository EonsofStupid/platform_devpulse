#!/usr/bin/env node
/**
 * @file generate-preset-catalog.mjs
 * @package @devpulse/coldlight
 *
 * Writes ColdLight's preset catalog (id, family, variant, label,
 * description) from the one preset source, the DTCG family files
 * `tokens/src/presets/*.tokens.json` (plan 0006 0s.2). A preset is a group
 * under `preset` that carries `$extensions["com.coldlight"].label`; its
 * state groups (`-hover`, `-active`, …) carry none. Run by build.mjs.
 */

import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const SOURCES = join(import.meta.dirname, 'tokens/src/presets');
const OUT_DIR = '../../packages/coldlight/presets/generated';
const EXT = 'com.coldlight';

export function presetCatalogArtifact() {
	const entries = [];
	for (const file of readdirSync(SOURCES).filter((f) => f.endsWith('.tokens.json')).sort()) {
		const { preset = {} } = JSON.parse(readFileSync(join(SOURCES, file), 'utf-8'));
		for (const [id, group] of Object.entries(preset)) {
			const meta = group?.$extensions?.[EXT];
			if (!meta?.label) continue;
			// `$description` reads "<id>: <text>"; the catalog keeps the text.
			const description = String(group.$description ?? '').replace(new RegExp(`^${id}:\\s*`), '');
			entries.push({ id, family: meta.family, variant: meta.variant, label: meta.label, description });
		}
	}

	// One key per line, as Biome formats it, so the generated file passes the package's checks.
	const field = ([key, value]) => `\t\t${key}: ${JSON.stringify(value)},`;
	const body = entries.map((e) => `\t{\n${Object.entries(e).map(field).join('\n')}\n\t},`).join('\n');
	const source = `/* AUTO-GENERATED by scripts/build/styledictionary/generate-preset-catalog.mjs — DO NOT EDIT */
/* Source: tokens/src/presets/*.tokens.json (the one preset source, plan 0006 0s.2) */

import type { PresetEntry } from "../schema.js";

export const PRESET_ENTRIES: readonly PresetEntry[] = [
${body}
];
`;

	return { destination: join(OUT_DIR, 'catalog.ts'), output: source };
}
