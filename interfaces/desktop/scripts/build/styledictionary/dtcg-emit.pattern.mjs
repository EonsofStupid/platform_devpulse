#!/usr/bin/env node
/**
 * @file dtcg-emit.pattern.mjs
 * @package @devpulse/coldlight
 *
 * Golden-pattern file writer. Emits THREE reference token files using
 * dtcg-emit.mjs helpers so the author can eyeball the on-disk shape
 * against DTCG 2025.10 before touching the main generator:
 *
 *   1. primitives/color/brand/teal.tokens.json            — colour ramp
 *   2. primitives/dimension/radius.tokens.json            — static dimensions
 *   3. primitives/shadow/depth.tokens.json                — shadow composite
 *
 * This script is read-only to anyone who doesn't run it. No globbing,
 * no automatic invocation. Not part of the build pipeline. Exists only
 * for pattern verification.
 *
 * Usage:
 *   node scripts/build/styledictionary/dtcg-emit.pattern.mjs
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
	dtcgColor,
	dtcgDimension,
	dtcgShadow,
	dtcgShadowLayer,
	oklchToHex,
} from './dtcg-emit.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const TOKENS_ROOT = resolve(__dirname, '../../../src/lib/design/tokens/src');

function writeToken(relPath, token) {
	const full = resolve(TOKENS_ROOT, relPath);
	mkdirSync(dirname(full), { recursive: true });
	writeFileSync(full, `${JSON.stringify(token, null, '\t')}\n`, 'utf8');
	console.log(`wrote ${relPath}`);
}

// ─────────────────────────────────────────────────────────────────
// 1. primitives/color/brand/teal.tokens.json
//    DevPulse primary brand. 11 stops, hue 173°, chroma 0.08.
// ─────────────────────────────────────────────────────────────────

const TEAL_STOPS = [
	{ key: '50', L: 0.97 },
	{ key: '100', L: 0.89 },
	{ key: '200', L: 0.81 },
	{ key: '300', L: 0.73 },
	{ key: '400', L: 0.65 },
	{ key: '500', L: 0.55 },
	{ key: '600', L: 0.46 },
	{ key: '700', L: 0.37 },
	{ key: '800', L: 0.28 },
	{ key: '900', L: 0.19 },
	{ key: '950', L: 0.12 },
];

const tealStops = {};
for (const { key, L } of TEAL_STOPS) {
	tealStops[key] = {
		$value: dtcgColor({
			colorSpace: 'oklch',
			components: [L, 0.08, 173],
			hex: oklchToHex(L, 0.08, 173),
		}),
		$description: `Teal lightness ${L} — OKLCH (${L} 0.08 173).`,
	};
}

const tealFile = {
	$description:
		'GENERATED by dtcg-emit.pattern.mjs — DO NOT HAND-EDIT. DevPulse primary brand scale. Hue 173°, chroma 0.08, 11 perceptually-uniform lightness stops.',
	teal: {
		$type: 'color',
		$description: 'DevPulse primary brand — perceptually uniform OKLCH teal scale.',
		...tealStops,
	},
};

writeToken('primitives/color/brand/teal.tokens.json', tealFile);

// ─────────────────────────────────────────────────────────────────
// 2. primitives/dimension/radius.tokens.json
//    Static border-radius scale. DTCG dimension objects.
// ─────────────────────────────────────────────────────────────────

const radiusFile = {
	$description:
		'GENERATED by dtcg-emit.pattern.mjs — DO NOT HAND-EDIT. Static border-radius scale in rem.',
	radius: {
		$type: 'dimension',
		$description: 'Border-radius tokens. Static rem values — no fluid math.',
		none: {
			$value: dtcgDimension(0, 'rem'),
			$description: 'No radius — sharp corners.',
		},
		xs: {
			$value: dtcgDimension(0.125, 'rem'),
			$description: 'Extra-small radius — 2 px equivalent.',
		},
		sm: {
			$value: dtcgDimension(0.25, 'rem'),
			$description: 'Small radius — 4 px.',
		},
		md: {
			$value: dtcgDimension(0.5, 'rem'),
			$description: 'Medium radius — 8 px. Default button / input radius.',
		},
		lg: {
			$value: dtcgDimension(0.75, 'rem'),
			$description: 'Large radius — 12 px. Cards and panels.',
		},
		xl: {
			$value: dtcgDimension(1, 'rem'),
			$description: 'Extra-large radius — 16 px. Overlays and sheets.',
		},
		'2xl': {
			$value: dtcgDimension(1.5, 'rem'),
			$description: 'Double extra-large radius — 24 px.',
		},
		full: {
			$value: dtcgDimension(624.9375, 'rem'),
			$description: 'Pill / circle radius — effectively infinite.',
		},
	},
};

writeToken('primitives/dimension/radius.tokens.json', radiusFile);

// ─────────────────────────────────────────────────────────────────
// 3. primitives/shadow/depth.tokens.json
//    z0..z4 elevation shadow stack. DTCG shadow composite (array).
//    Multipliers match the existing generator: [0, 1, 3, 10, 15].
// ─────────────────────────────────────────────────────────────────

const SHADOW_BASE_OFFSET = 0.0625; // rem — 1 px at base=16
const SHADOW_BASE_BLUR = 0.1875; // rem — 3 px
const SHADOW_COLOR = [0.2, 0.01, 224]; // oklch dark blue-black
const SHADOW_HEX = oklchToHex(...SHADOW_COLOR);
const SHADOW_MULTIPLIERS = [0, 1, 3, 10, 15];

const depthStops = {};

for (let z = 0; z < SHADOW_MULTIPLIERS.length; z++) {
	const m = SHADOW_MULTIPLIERS[z];
	if (z === 0) {
		// z0 = no elevation. DTCG has no "none" shadow type — emit an
		// empty single-layer shadow with transparent colour so the CSS
		// transform produces `box-shadow: none` downstream.
		depthStops.z0 = {
			$value: dtcgShadowLayer({
				color: dtcgColor({
					colorSpace: 'oklch',
					components: SHADOW_COLOR,
					alpha: 0,
					hex: SHADOW_HEX,
				}),
				offsetX: dtcgDimension(0, 'rem'),
				offsetY: dtcgDimension(0, 'rem'),
				blur: dtcgDimension(0, 'rem'),
				spread: dtcgDimension(0, 'rem'),
			}),
			$description: 'No elevation — flat surface.',
		};
		continue;
	}
	const oy = SHADOW_BASE_OFFSET * m;
	const bl = SHADOW_BASE_BLUR * m;
	const oy2 = oy * 0.3;
	const bl2 = bl * 0.5;
	depthStops[`z${z}`] = {
		$value: dtcgShadow([
			dtcgShadowLayer({
				color: dtcgColor({
					colorSpace: 'oklch',
					components: SHADOW_COLOR,
					alpha: 0.15,
					hex: SHADOW_HEX,
				}),
				offsetX: dtcgDimension(0, 'rem'),
				offsetY: dtcgDimension(oy, 'rem'),
				blur: dtcgDimension(bl, 'rem'),
				spread: dtcgDimension(0, 'rem'),
			}),
			dtcgShadowLayer({
				color: dtcgColor({
					colorSpace: 'oklch',
					components: SHADOW_COLOR,
					alpha: 0.1,
					hex: SHADOW_HEX,
				}),
				offsetX: dtcgDimension(0, 'rem'),
				offsetY: dtcgDimension(oy2, 'rem'),
				blur: dtcgDimension(bl2, 'rem'),
				spread: dtcgDimension(0, 'rem'),
			}),
		]),
		$description: `Elevation z${z} — multiplier ${m}× base offset/blur. Two layered drop shadows.`,
	};
}

const shadowFile = {
	$description:
		'GENERATED by dtcg-emit.pattern.mjs — DO NOT HAND-EDIT. Elevation shadow stack z0..z4. DTCG shadow composite, two-layer stacks per level except z0.',
	depth: {
		$type: 'shadow',
		$description:
			'Neumorphic elevation shadows. Each level is a two-layer drop shadow stack with diminishing alpha on the secondary layer.',
		...depthStops,
	},
};

writeToken('primitives/shadow/depth.tokens.json', shadowFile);

console.log('\n═══ pattern files emitted ═══');
