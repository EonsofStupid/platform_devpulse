#!/usr/bin/env node
/**
 * @file generate-scales.mjs
 * @package @devpulse/coldlight
 *
 * Tier-1 primitive token generator — DTCG 2025.10 compliant multi-file writer.
 *
 * The SSOT for every DevPulse primitive — colour ramps, gradients,
 * fluid dimensions, motion scales, shadow stacks, z-index, opacity,
 * typography — all derived from formulas and tables here, emitted as
 * `.tokens.json` files under `tokens/src/primitives/**` with matching
 * TS barrels.
 *
 * DTCG spec reference:
 *   interfaces/desktop/src/lib/design/docs/DTCG-REFERENCE.md
 *
 * Golden pattern reference:
 *   interfaces/desktop/scripts/build/styledictionary/dtcg-emit.mjs
 *   interfaces/desktop/scripts/build/styledictionary/dtcg-emit.probe.mjs
 *
 * ## Architecture
 *
 * 1. DATA section — hue lists, multiplier tables, scale definitions.
 *    Hand-authored constants. No logic.
 * 2. BUILDERS — one per token category. Pure functions that take data
 *    and return a DTCG file object `{ $description, <group>: {...} }`.
 * 3. MANIFEST — the single array describing every file to emit, with
 *    its relative path and the builder that produces it.
 * 4. WRITE — walks the manifest, writes every `.tokens.json` file,
 *    emits TS barrels per category folder.
 *
 * ## What changed vs the pre-rewrite generator
 *
 * - Output: no more monolithic `generated-scales.tokens.json`. Every
 *   hue / scale / stack lives in its own file for junior legibility.
 * - Emit shape: every `$value` is a DTCG object (Color Module,
 *   dimension { value, unit }, cubicBezier array, shadow composite,
 *   gradient stop array) — no more CSS-string stringification.
 * - Fluid dimensions: the DTCG authoritative value is the MAX (ceiling);
 *   the clamp math travels in `$extensions.com.devpulse.coldlight.fluid`
 *   for the SD5 transform to rebuild.
 * - TS barrels: each category folder gets a generated `index.ts` that
 *   imports every leaf JSON by name and re-exports a typed object.
 * - Generator warning: every emitted JSON opens with a `$description`
 *   that says "GENERATED by generate-scales.mjs — DO NOT HAND-EDIT".
 *
 * Usage:
 *   node scripts/build/styledictionary/generate-scales.mjs
 *   pnpm ds:tokens:build   # downstream SD5 step, reads the emitted files
 */

