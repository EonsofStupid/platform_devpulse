/** Build the elevation shadow file — two-layer stacks per z level. */
function buildShadowDepthFile() {
	const hex = oklchToHex(...SHADOW_COLOR);
	const children = {};
	for (let z = 0; z < SHADOW_MULTIPLIERS.length; z++) {
		const m = SHADOW_MULTIPLIERS[z];
		if (z === 0) {
			children.z0 = {
				$value: dtcgShadowLayer({
					color: dtcgColor({
						colorSpace: 'oklch',
						components: SHADOW_COLOR,
						alpha: 0,
						hex,
					}),
					offsetX: dtcgDimension(0, 'rem'),
					offsetY: dtcgDimension(0, 'rem'),
					blur: dtcgDimension(0, 'rem'),
					spread: dtcgDimension(0, 'rem'),
				}),
				$description: 'No elevation — flat surface.',
			};
			continue;
		}
		const oy = SHADOW_BASE_OFFSET * m;
		const bl = SHADOW_BASE_BLUR * m;
		const oy2 = oy * 0.3;
		const bl2 = bl * 0.5;
		children[`z${z}`] = {
			$value: dtcgShadow([
				dtcgShadowLayer({
					color: dtcgColor({
						colorSpace: 'oklch',
						components: SHADOW_COLOR,
						alpha: 0.15,
						hex,
					}),
					offsetX: dtcgDimension(0, 'rem'),
					offsetY: dtcgDimension(oy, 'rem'),
					blur: dtcgDimension(bl, 'rem'),
					spread: dtcgDimension(0, 'rem'),
				}),
				dtcgShadowLayer({
					color: dtcgColor({
						colorSpace: 'oklch',
						components: SHADOW_COLOR,
						alpha: 0.1,
						hex,
					}),
					offsetX: dtcgDimension(0, 'rem'),
					offsetY: dtcgDimension(oy2, 'rem'),
					blur: dtcgDimension(bl2, 'rem'),
					spread: dtcgDimension(0, 'rem'),
				}),
			]),
			$description: `Elevation z${z} — multiplier ${m}× base offset/blur, two layered drop shadows.`,
		};
	}
	return {
		$description: HEADER_WARNING,
		depth: {
			$type: 'shadow',
			$description:
				'Neumorphic elevation stack z0..z4. Each level is a two-layer drop shadow with diminishing alpha on the secondary layer.',
			...children,
		},
	};
}

