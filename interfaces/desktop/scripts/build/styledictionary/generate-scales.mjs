/**
 * Build a DTCG colour ramp file. Every stop uses the shared
 * RAMP_LIGHTNESS sweep with the supplied hue and chroma.
 *
 * Result shape:
 * ```
 * {
 *   $description: '<generator warning>',
 *   <hueId>: {
 *     $type: 'color',
 *     $description: '<hue description>',
 *     '50':  { $value: {...}, $description: '...' },
 *     ...
 *   }
 * }
 * ```
 */
function buildColorRampFile({ id, hue, chroma, description }) {
	const stops = {};
	for (let i = 0; i < RAMP_STOPS.length; i++) {
		const key = RAMP_STOPS[i];
		const L = RAMP_LIGHTNESS[i];
		stops[key] = {
			$value: dtcgColor({
				colorSpace: 'oklch',
				components: [L, chroma, hue],
				hex: oklchToHex(L, chroma, hue),
			}),
			$description: `${id} ${key} — lightness ${L}.`,
		};
	}
	return {
		$description: HEADER_WARNING,
		color: {
			[id]: {
				$type: 'color',
				$description: description,
				...stops,
			},
		},
	};
}

