// ═══════════════════════════════════════════════════════════════

function main() {
	// Start clean — blow away the entire generated primitives tree so
	// deleted hues / renamed categories don't leave orphans behind.
	// Hand-authored Tier 2/3 files live OUTSIDE primitives/ so they
	// are untouched.
	rmSync(PRIMITIVES_ROOT, { recursive: true, force: true });

	let tokenCount = 0;
	for (const entry of MANIFEST) {
		const payload = entry.build();
		writeJsonFile(entry.path, payload);
		// Rough token count — every `$value` key in the serialized JSON
		// is one token. Quick visual metric for the reviewer.
		tokenCount += (JSON.stringify(payload).match(/"\$value"/g) ?? []).length;
	}

	writeAllBarrels();
	removeLegacyMonolith();

	console.log(`[generate-scales] wrote ${MANIFEST.length} files, ${tokenCount} tokens`);
}

main();
