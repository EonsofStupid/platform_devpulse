/** Write one `.tokens.json` file. Creates parent directories as needed. */
function writeJsonFile(relPath, payload) {
	const full = resolve(TOKENS_ROOT, relPath);
	mkdirSync(dirname(full), { recursive: true });
	writeFileSync(full, `${JSON.stringify(payload, null, '\t')}\n`, 'utf8');
}

/**
 * Convert a dashed identifier (`brand-cyan`, `z-index`) to a valid
 * JS identifier for the barrel import name. `brand-cyan` → `brandCyan`.
 */
function toIdent(id) {
	return id.replace(/-([a-z0-9])/g, (_, ch) => ch.toUpperCase());
}

/**
 * Write a TS barrel file for a category folder. Imports every leaf
 * JSON by name and re-exports them as a typed object. The generated
 * file carries the same DO-NOT-HAND-EDIT banner as the JSON files.
 */
function writeBarrel(categoryRelDir, entries) {
	const full = resolve(TOKENS_ROOT, categoryRelDir, 'index.ts');
	mkdirSync(dirname(full), { recursive: true });

	const sorted = [...entries].sort((a, b) => a.key.localeCompare(b.key));
	const imports = sorted
		.map((e) => {
			const fileName = e.path.split('/').pop();
			return `import ${toIdent(e.key)}Leaf from './${fileName}' with { type: 'json' };`;
		})
		.join('\n');

	// primitives/gradient/** files wrap leaves in { gradient: { <subcat>: { key: ... } } }.
	// Everything else still emits the leaf as a top-level property.
	const gradientMatch = categoryRelDir.match(/^primitives\/gradient\/([^/]+)$/);
	const gradientSubcat = gradientMatch ? gradientMatch[1] : null;
	const accessor = gradientSubcat
		? (key) => `${toIdent(key)}Leaf.gradient.${gradientSubcat}['${key}']`
		: (key) => `${toIdent(key)}Leaf['${key}']`;

	const members = sorted
		.map((e) => `\t'${e.key}': ${accessor(e.key)},`)
		.join('\n');

	const body = `/**
 * @file ${categoryRelDir}/index.ts
 * @package @devpulse/coldlight
 *
 * GENERATED by generate-scales.mjs — DO NOT HAND-EDIT. Modify the
 * generator at scripts/build/styledictionary/generate-scales.mjs and
 * re-run pnpm ds:generate-scales.
 *
 * Typed barrel for the ${categoryRelDir} category. Imports every
 * leaf JSON file by name and re-exports them as a single object so
 * consumers get autocomplete for every token atom in this category.
 */

${imports}

export const ${toIdent(categoryRelDir.split('/').pop() ?? 'tokens')} = {
${members}
} as const;
`;

	writeFileSync(full, body, 'utf8');
}

/**
 * Group manifest entries by category folder and write one barrel per
 * category.
 */
function writeAllBarrels() {
	const byCategory = new Map();
	for (const entry of MANIFEST) {
		if (!byCategory.has(entry.category)) byCategory.set(entry.category, []);
		byCategory.get(entry.category).push(entry);
	}
	for (const [category, entries] of byCategory) {
		writeBarrel(category, entries);
	}
}

/**
 * Delete the legacy monolithic output file if it still exists. This
 * lines up with the pre-release rewrite policy — no backwards compat,
 * the old file is replaced, not deprecated.
 */
function removeLegacyMonolith() {
	const legacy = resolve(TOKENS_ROOT, 'generated-scales.tokens.json');
	try {
		rmSync(legacy, { force: true });
	} catch {
		/* already gone */
	}
}

