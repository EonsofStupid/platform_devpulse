/**
 * Build a "surface" gradient — subtle top-to-bottom depth shift,
 * derived from the base lightness + 0.04 to base - 0.02.
 */
function buildSurfaceGradientFile({ id, hue, chroma, baseL }) {
	const topL = round(baseL + 0.04);
	const bottomL = round(baseL - 0.02);
	return {
		$description: HEADER_WARNING,
		gradient: {
			surface: {
				[id]: dtcgGradientToken(
					[
						dtcgGradientStop(
							dtcgColor({
								colorSpace: 'oklch',
								components: [topL, chroma, hue],
								hex: oklchToHex(topL, chroma, hue),
							}),
							0,
						),
						dtcgGradientStop(
							dtcgColor({
								colorSpace: 'oklch',
								components: [bottomL, chroma, hue],
								hex: oklchToHex(bottomL, chroma, hue),
							}),
							1,
						),
					],
					{ kind: 'linear', angle: 180 },
					`${id} surface depth gradient — subtle top-to-bottom lightness shift.`,
				),
			},
		},
	};
}

