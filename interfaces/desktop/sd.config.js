/**
 * coldlight/tailwind-theme
 * Reads SD5 dictionary.allTokens, maps each token through themeMappings,
 * outputs a Tailwind v4 @theme block with proper namespace prefixing.
 */
function tailwindThemeFormat({ dictionary }) {
	const lines = [
		"/**",
		" * AUTO-GENERATED by Style Dictionary v5 — DO NOT EDIT",
		" * Tailwind v4 @theme block",
		" * Source: sd.config.js → coldlight/tailwind-theme format",
		" */",
		"",
		"@theme {",
	];

	for (const token of dictionary.allTokens) {
		const group = token.path[0];
		const mapping = themeMappings[group];
		if (!mapping) continue;

		const value = token.$value ?? token.value;
		const suffix = token.path.slice(1).join("-");
		const varKey = mapping.prefix
			? `--${mapping.namespace}-${mapping.prefix}-${suffix}`
			: `--${mapping.namespace}-${suffix}`;

		lines.push(`\t${varKey}: ${value};`);
	}

	lines.push("}");
	lines.push("");
	return lines.join("\n");
}

/**
 * coldlight/types
 * Reads SD5 dictionary, groups tokens by top-level DTCG group,
 * outputs TypeScript readonly arrays + union types per group.
 */
function typesFormat({ dictionary }) {
	const lines = [
		"/**",
		" * AUTO-GENERATED by Style Dictionary v5 — DO NOT EDIT",
		" * TypeScript token types + readonly arrays",
		" * Source: sd.config.js → coldlight/types format",
		" */",
		"",
	];

	// Group tokens by their top-level DTCG group
	const groups = new Map();
	for (const token of dictionary.allTokens) {
		const group = token.path[0];
		if (!groups.has(group)) groups.set(group, []);
		groups.get(group).push(token);
	}

	for (const [group, tokens] of groups) {
		const pascal = group.charAt(0).toUpperCase() + group.slice(1);
		// Use the leaf key (last path segment) as the enum value
		const values = tokens.map((t) => t.path[t.path.length - 1]);
		const unique = [...new Set(values)];
		const serialized = JSON.stringify(unique);

		lines.push(`export const ${pascal}Tokens = ${serialized} as const;`);
		lines.push(`export type ${pascal}Token = (typeof ${pascal}Tokens)[number];`);
		lines.push("");
	}

	lines.push("export const TokenArrays = {");
	for (const group of groups.keys()) {
		const pascal = group.charAt(0).toUpperCase() + group.slice(1);
		lines.push(`\t${group}: ${pascal}Tokens,`);
	}
	lines.push("} as const;");
	lines.push("");

	return lines.join("\n");
}

