<!--
  @file primitives/dialog/Root.svelte
  @layer primitives

  Dialog root - manages open/closed state and generates ColdLight-owned IDs.

  ColdLight OWNS:
  - ALL IDs (contentId, titleId, descriptionId) via useId()
  - ID sharing via Svelte context

  meltui provides ONLY:
  - State management (open/close coordination)

  Data Attributes:
  - data-kind="dialog"
  - data-slot="root"
  - data-state="open" | "closed"
-->
<script lang="ts">
import { Dialog, useId } from "meltui";
import { setContext } from "svelte";
import type { DialogContext, DialogRootProps, DialogState } from "./types.js";
import { DIALOG_CONTEXT_KEY } from "./types.js";

let {
	open = $bindable(false),
	onOpenChange,
	children,
	"data-id": dataId,
}: DialogRootProps = $props();

// ============================================
// COLDLIGHT OWNS ALL IDs
// ============================================
// Generated by ColdLight using useId() - NOT from meltui internal state
const contentId = useId();
const titleId = useId();
const descriptionId = useId();

// ============================================
// COLDLIGHT SHARES IDs VIA CONTEXT
// ============================================
// Children (Content, Title, Description, Trigger) access these IDs
const dialogContext: DialogContext = {
	contentId,
	titleId,
	descriptionId,
	open: () => open,
};
setContext<DialogContext>(DIALOG_CONTEXT_KEY, dialogContext);

// ============================================
// COLDLIGHT DERIVES STATE
// ============================================
const dataState: DialogState = $derived(open ? "open" : "closed");
</script>

<div
  data-kind="dialog"
  data-slot="root"
  data-state={dataState}
  data-id={dataId}
>
  <Dialog.Root bind:open {onOpenChange}>
    {#if children}
      {@render children()}
    {/if}
  </Dialog.Root>
</div>
