// Helper for nested component tokens
function generateComponentTokens(
  obj: Record<string, unknown>,
  prefix: string,
  lines: string[],
  depth = 0
): void {
  for (const [key, value] of Object.entries(obj)) {
    const varName = `${prefix}-${kebabCase(key)}`;
    if (value && typeof value === "object" && "l" in value) {
      // It's an OklchColor
      lines.push(`  ${varName}: ${oklchToCSS(value as OklchColor)};`);
    } else if (value && typeof value === "object") {
      // Nested object
      generateComponentTokens(value as Record<string, unknown>, varName, lines, depth + 1);
    }
  }
}

// ===========================================
// VIOLATION CHECKER
// ===========================================

function checkViolations(code: string, filePath: string): Violation[] {
  const violations: Violation[] = [];
  const lines = code.split("\n");

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const lineNum = i + 1;

    // Check for arbitrary Tailwind values
    const arbitraryMatch = line.match(/class="[^"]*\[([^\]]+)\][^"]*"/);
    if (arbitraryMatch) {
      violations.push({
        file: filePath,
        line: lineNum,
        column: line.indexOf(arbitraryMatch[1]),
        type: "arbitrary-value",
        found: arbitraryMatch[1],
        suggestion: "Use a token-backed class instead",
      });
    }

    // Check for CSS variable definitions (--something:)
    const cssVarDefMatch = line.match(/--[\w-]+\s*:/);
    if (cssVarDefMatch && !line.includes("var(")) {
      violations.push({
        file: filePath,
        line: lineNum,
        column: line.indexOf(cssVarDefMatch[0]),
        type: "css-var-definition",
        found: cssVarDefMatch[0],
        suggestion: "Component-scoped CSS variables are not allowed",
      });
    }

    // Check for inline styles with colors
    const inlineStyleMatch = line.match(/style="[^"]*(?:color|background|border)[^"]*"/i);
    if (inlineStyleMatch) {
      violations.push({
        file: filePath,
        line: lineNum,
        column: line.indexOf(inlineStyleMatch[0]),
        type: "inline-style",
        found: inlineStyleMatch[0],
        suggestion: "Use data-* attributes and recipe CSS instead",
      });
    }

    // Check for raw color values
    const rawColorMatch = line.match(/(#[0-9a-fA-F]{3,8}|rgb\([^)]+\)|rgba\([^)]+\)|hsl\([^)]+\)|oklch\([^)]+\))/);
    if (rawColorMatch && !line.includes("var(--dp-")) {
      violations.push({
        file: filePath,
        line: lineNum,
        column: line.indexOf(rawColorMatch[0]),
        type: "raw-color",
        found: rawColorMatch[0],
        suggestion: "Use a token reference: var(--dp-*)",
      });
    }
  }

  return violations;
}

