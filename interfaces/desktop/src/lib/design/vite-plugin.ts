export function coldlight(options: ColdLightOptions = {}): Plugin {
  let config: ResolvedConfig;
  let designDir: string;
  let tokensPath: string;

  return {
    name: "vite-plugin-coldlight",
    enforce: "pre",

    configResolved(resolvedConfig) {
      config = resolvedConfig;
      // Auto-detect design directory
      designDir = path.resolve(config.root, "src/lib/design");
      tokensPath = options.tokensPath || path.join(designDir, "tokens/tokens.ts");
    },

    async buildStart() {
      console.log("[coldlight] Generating tokens...");
      try {
        await generateFromTokens(tokensPath, designDir);
        console.log("[coldlight] ✅ Tokens generated successfully");
      } catch (err) {
        console.error("[coldlight] ❌ Token generation failed:", err);
        throw err;
      }
    },

    async handleHotUpdate({ file }) {
      if (file.endsWith("tokens/tokens.ts")) {
        console.log("[coldlight] tokens.ts changed, regenerating...");
        try {
          await generateFromTokens(tokensPath, designDir);
          console.log("[coldlight] ✅ Tokens regenerated");
        } catch (err) {
          console.error("[coldlight] ❌ Token regeneration failed:", err);
        }
      }
    },

    transform(code, id) {
      if (options.skipValidation) return null;

      // Only validate .svelte files in design system directories
      const validatePaths = options.validatePaths || [
        "primitives",
        "components",
        "renderers",
      ];

      const shouldValidate = validatePaths.some(
        (p) => id.includes(`/design/${p}/`) && id.endsWith(".svelte")
      );

      if (!shouldValidate) return null;

      const violations = checkViolations(code, id);

      if (violations.length > 0) {
        const errorMessages = violations.map((v) => {
          return `[coldlight] VIOLATION in ${v.file}:${v.line}:${v.column}
  Type: ${v.type}
  Found: ${v.found}
  ${v.suggestion ? `Suggestion: ${v.suggestion}` : ""}`;
        });

        this.error(errorMessages.join("\n\n"));
      }

      return null;
    },
  };
}

export default coldlight;
