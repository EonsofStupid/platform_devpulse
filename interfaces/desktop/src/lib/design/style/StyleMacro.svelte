<!--
	@component StyleMacro
	@package @devpulse/coldlight

	THE visual resolution component for ColdLight.

	11-axis visual system (each = 1 real DTCG $type):
	  backgroundColor, backgroundBlur, shadow, border, animation, transition,
	  typography, gradient, color, borderRadius, opacity

	Consumes expanded DTCG style tokens generated by SD5.
	Constructs var() references from style ID + axis name.
	Assembles composite shorthands from expanded sub-properties.
	Outputs --cl-* CSS custom properties on wrapper div.
	Glue CSS on [data-kind] consumes --cl-* vars → browser paints.
-->
<script lang="ts">
import type { Snippet } from "svelte";
import { platformBase } from "./base-state.svelte.js";

interface Props {
	/** Component kind — for VPB identification + glue CSS targeting. */
	kind?: string;
	/** Style ID — references a DTCG token group (e.g. "button-primary"). */
	style?: string;
	/** Content to wrap. */
	children: Snippet;
	/** Additional CSS class on the wrapper (structural layout only). */
	class?: string;
}

let {
	kind,
	style: styleId,
	children,
	class: className,
}: Props = $props();

/**
 * Build --cl-* CSS custom properties from the style ID.
 * Each --cl-* var references expanded SD5 output: var(--style-{styleId}-{axis-name}).
 * Composites are assembled into CSS shorthand from their expanded sub-properties.
 */
let resolved = $derived.by(() => {
	const id = styleId ?? platformBase.activeStyleId;
	if (!id) return { css: "", encoding: "" };

	const p = `--style-${id}`;

	// Simple axes: direct var() reference
	const bg = `--cl-bg: var(${p}-background-color)`;
	const blur = `--cl-blur: var(${p}-background-blur, 0)`;
	const anim = `--cl-animation: var(${p}-animation, none)`;
	const fg = `--cl-color: var(${p}-color, inherit)`;
	const radius = `--cl-radius: var(${p}-border-radius, 0)`;
	const opacity = `--cl-opacity: var(${p}-opacity, 1)`;

	// Border (expanded → assembled)
	const borderWidth = `var(${p}-border-width, 0)`;
	const borderStyle = `var(${p}-border-style, none)`;
	const borderColor = `var(${p}-border-color, transparent)`;
	const border = `--cl-border: ${borderWidth} ${borderStyle} ${borderColor}`;

	// Transition (expanded → assembled)
	const transDur = `var(${p}-transition-duration, 0ms)`;
	const transDelay = `var(${p}-transition-delay, 0ms)`;
	const transEase = `var(${p}-transition-timing-function, ease)`;
	const transition = `--cl-transition: all ${transDur} ${transEase} ${transDelay}`;

	// Typography (expanded → individual CSS properties, no shorthand)
	const fontFamily = `--cl-font-family: var(${p}-typography-font-family, inherit)`;
	const fontSize = `--cl-font-size: var(${p}-typography-font-size, inherit)`;
	const fontWeight = `--cl-font-weight: var(${p}-typography-font-weight, inherit)`;
	const letterSpacing = `--cl-letter-spacing: var(${p}-typography-letter-spacing, 0)`;
	const lineHeight = `--cl-line-height: var(${p}-typography-line-height, inherit)`;

	// Shadow (expanded, multi-layer — assemble from indexed sub-properties)
	// SD5 generates shadow-1-*, shadow-2-* for array shadows, or shadow-* for single
	// Use the first two layers (most shadows are 1-2 layers)
	const s1ox = `var(${p}-shadow-1-offset-x, ${p}-shadow-offset-x, 0)`;
	const s1oy = `var(${p}-shadow-1-offset-y, var(${p}-shadow-offset-y, 0))`;
	const s1b = `var(${p}-shadow-1-blur, var(${p}-shadow-blur, 0))`;
	const s1s = `var(${p}-shadow-1-spread, var(${p}-shadow-spread, 0))`;
	const s1c = `var(${p}-shadow-1-color, var(${p}-shadow-color, transparent))`;
	const shadow = `--cl-shadow: ${s1ox} ${s1oy} ${s1b} ${s1s} ${s1c}`;

	// Gradient — SD5 processes via custom transform, or empty
	const gradient = `--cl-gradient: var(${p}-gradient, none)`;

	const css = [
		bg, blur, anim, fg, radius, opacity,
		border, transition, shadow, gradient,
		fontFamily, fontSize, fontWeight, letterSpacing, lineHeight,
	].join("; ");

	const encoding = id;

	return { css, encoding };
});
</script>

<div
	data-macro-id={styleId}
	data-macro-kind={kind}
	data-encoding={resolved.encoding || undefined}
	class={className || undefined}
	style={resolved.css || undefined}
>
	{@render children()}
</div>
