/**
 * @file Svelte Code Generator — BlockNode[] → .svelte source
 * @layer vpb
 * @package @devpulse/sys
 *
 * Converts a BlockNode tree into a valid .svelte file.
 * Uses resolveClasses() to produce shortcode class strings.
 */

import type { BlockNode } from "$lib/design/blocks/schema.js";
import { resolveClasses } from "$lib/design/renderers/resolveClasses.js";

/**
 * Generate a .svelte file from a BlockNode tree.
 * Produces a self-contained component with all shortcode classes resolved.
 */
export function generateSvelte(roots: BlockNode[]): string {
	const lines: string[] = [];

	lines.push("<!-- Generated by VPB -->");
	lines.push("");

	const body = roots.map((root) => renderNode(root, 0)).join("\n");
	lines.push(body);

	return lines.join("\n") + "\n";
}

function renderNode(node: BlockNode, indent: number): string {
	const classes = resolveClasses(node);
	const rootClass = classes["root"] ?? classes["content"] ?? Object.values(classes)[0] ?? "";
	const tab = "\t".repeat(indent);
	const lines: string[] = [];

	const slotEntries = node.slots ? Object.entries(node.slots) : [];
	const hasChildren = slotEntries.some(([, children]) => children.length > 0);

	if (!hasChildren) {
		lines.push(`${tab}<div class="${rootClass}" data-kind="${node.kind}"></div>`);
	} else {
		lines.push(`${tab}<div class="${rootClass}" data-kind="${node.kind}">`);
		for (const [, children] of slotEntries) {
			for (const child of children) {
				lines.push(renderNode(child, indent + 1));
			}
		}
		lines.push(`${tab}</div>`);
	}

	return lines.join("\n");
}

/**
 * Generate and trigger download of a .svelte file.
 */
export function downloadSvelte(roots: BlockNode[], filename = "page.svelte"): void {
	const source = generateSvelte(roots);
	const blob = new Blob([source], { type: "text/plain" });
	const url = URL.createObjectURL(blob);
	const a = document.createElement("a");
	a.href = url;
	a.download = filename;
	a.click();
	URL.revokeObjectURL(url);
}
