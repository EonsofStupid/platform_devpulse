/**
 * @file Svelte Code Generator — BlockNode[] → .svelte source
 * @layer vpb
 * @package @devpulse/sys
 *
 * Converts a BlockNode tree into a valid .svelte file. Each node becomes an
 * element carrying what ColdLight's base CSS styles from: `data-kind`, the
 * `data-cl-*` family markers and the canonical variables (`renderForge` for
 * the node's preset, its axis props on top). Replaces the recipe class
 * strings `resolveClasses()` produced before 0020c1f4.
 */

import type { BlockNode } from "@devpulse/coldlight/blocks";
import { type AxisContext, resolveNode, type VpbProps } from "../registry/vpb-axes.js";

/**
 * Generate a .svelte file from a BlockNode tree.
 */
export function generateSvelte(roots: BlockNode[], ctx: AxisContext): string {
	const lines: string[] = [];

	lines.push("<!-- Generated by VPB -->");
	lines.push("");

	const body = roots.map((root) => renderNode(root, 0, ctx)).join("\n");
	lines.push(body);

	return `${lines.join("\n")}\n`;
}

function attrsOf(node: BlockNode, ctx: AxisContext): string {
	const visual = resolveNode(node, node.props as VpbProps, ctx);
	const data = Object.entries(visual.dataAttrs)
		.map(([name, value]) => (value === "" ? name : `${name}="${value}"`))
		.join(" ");
	return `${data} style="${visual.style}"`;
}

function renderNode(node: BlockNode, indent: number, ctx: AxisContext): string {
	const tab = "\t".repeat(indent);
	const lines: string[] = [];
	const attrs = attrsOf(node, ctx);

	const slotEntries = node.slots ? Object.entries(node.slots) : [];
	const hasChildren = slotEntries.some(([, children]) => children.length > 0);

	if (!hasChildren) {
		lines.push(`${tab}<div ${attrs}></div>`);
	} else {
		lines.push(`${tab}<div ${attrs}>`);
		for (const [, children] of slotEntries) {
			for (const child of children) {
				lines.push(renderNode(child, indent + 1, ctx));
			}
		}
		lines.push(`${tab}</div>`);
	}

	return lines.join("\n");
}

/**
 * Generate and trigger download of a .svelte file.
 */
export function downloadSvelte(
	roots: BlockNode[],
	ctx: AxisContext,
	filename = "page.svelte",
): void {
	const source = generateSvelte(roots, ctx);
	const blob = new Blob([source], { type: "text/plain" });
	const url = URL.createObjectURL(blob);
	const a = document.createElement("a");
	a.href = url;
	a.download = filename;
	a.click();
	URL.revokeObjectURL(url);
}
