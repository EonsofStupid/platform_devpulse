//! Tauri build script for desktop backend.
//!
//! Also generates `routes.rs` in `OUT_DIR`: one constant per `SvelteKit` page
//! folder under `../src/routes` (group folders such as `(app)` dropped, as
//! `SvelteKit` drops them from the URL). Rust that opens a page names one of
//! these constants, so a page that does not exist does not compile
//! (plan 0008).

// Build scripts can only panic on errors — expect is the standard pattern.
#![allow(clippy::expect_used)]

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    generate_routes();
    tauri_build::build();
}

/// `/devtools/system/datastores/turso` → `DEVTOOLS_SYSTEM_DATASTORES_TURSO`; `/` → `ROOT`.
fn const_name(path: &str) -> String {
    if path == "/" {
        return "ROOT".to_owned();
    }
    path.trim_start_matches('/')
        .split(['/', '-'])
        .map(str::to_ascii_uppercase)
        .collect::<Vec<_>>()
        .join("_")
}

fn is_group(segment: &str) -> bool {
    segment.starts_with('(') && segment.ends_with(')')
}

/// Every folder under `dir` that holds a `+page.svelte`, as its URL path.
fn collect(root: &Path, dir: &Path, out: &mut Vec<String>) {
    for entry in fs::read_dir(dir).expect("route folder must be readable") {
        let path = entry.expect("route entry must be readable").path();
        if path.is_dir() {
            collect(root, &path, out);
        } else if path.file_name().is_some_and(|n| n == "+page.svelte") {
            let folder = path.parent().expect("a page lives in a folder");
            let rel = folder
                .strip_prefix(root)
                .expect("page is under the routes root");
            let segments: Vec<String> = rel
                .components()
                .map(|c| c.as_os_str().to_string_lossy().into_owned())
                .filter(|s| !is_group(s))
                .collect();
            out.push(format!("/{}", segments.join("/")));
        }
    }
}

fn generate_routes() {
    let root = Path::new("../src/routes");
    println!("cargo:rerun-if-changed=../src/routes");

    let mut paths = Vec::new();
    collect(root, root, &mut paths);
    paths.sort();
    paths.dedup();

    let mut out =
        String::from("// Generated by build.rs from ../src/routes (plan 0008). Do not edit.\n\n");
    for path in &paths {
        writeln!(
            out,
            "/// `{path}`\npub const {}: &str = \"{path}\";",
            const_name(path)
        )
        .expect("writing to a String cannot fail");
    }
    out.push_str("\n/// Every page path.\npub const ALL: &[&str] = &[\n");
    for path in &paths {
        writeln!(out, "    {},", const_name(path)).expect("writing to a String cannot fail");
    }
    out.push_str("];\n");

    let dest = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR must be set")).join("routes.rs");
    fs::write(dest, out).expect("routes.rs must be writable");
}
